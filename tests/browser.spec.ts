import { test, expect } from '@playwright/test';
test('customer payment submission, admin review, and protected PDF delivery',async({page},testInfo)=>{
  const phone=`9${String(Date.now()).slice(-8)}${testInfo.project.name==='mobile' ? '1' : '2'}`;
  const password='LocalStudent!2026';
  await page.goto('/'); await expect(page.getByRole('heading',{name:'A good place to start.'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByLabel('Search notes').fill('Physics');
  await page.getByRole('link',{name:'View Physics, made clear.'}).click();
  await page.getByRole('button',{name:'Get these notes'}).click();
  await page.getByLabel('Full name',{exact:true}).fill('Browser Test Student');
  await page.getByLabel('Phone number',{exact:true}).fill(phone);
  await page.getByLabel('Email address',{exact:true}).fill(`student-${phone}@example.test`);
  await page.locator('input[name=password]').fill(password);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByRole('button',{name:'Get these notes'}).click();
  await expect(page.getByText('Demo order — do not send money.',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByLabel('UPI transaction ID / UTR',{exact:true}).fill(`BROWSER${phone}`);
  await page.getByLabel('Payer name',{exact:true}).fill('Browser Test Student');
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Submit for verification'}).click();
  await expect(page.getByRole('heading',{name:'Awaiting admin verification'})).toBeVisible();
  const orderUrl=page.url();
  // Separate context preserves the customer's cookie while the admin reviews.
  const adminContext=await page.context().browser()!.newContext({baseURL:'http://127.0.0.1:8790',viewport:{width:390,height:844}});
  const adminPage=await adminContext.newPage();
  await adminPage.goto('/login?next=%2Fadmin%2Fnotifications');
  await adminPage.getByLabel('Phone number',{exact:true}).fill('9000000000');
  await adminPage.locator('input[name=password]').fill('LocalAdmin!2026');
  await adminPage.getByRole('button',{name:'Log in',exact:true}).click();
  const card=adminPage.locator('.review-card').filter({hasText:`BROWSER${phone}`});
  await card.getByRole('button',{name:'Review payment'}).click();
  await expect(adminPage.getByRole('button',{name:'Approve & unlock PDF'})).toBeDisabled();
  await adminPage.getByRole('checkbox').check();
  await adminPage.getByRole('button',{name:'Approve & unlock PDF'}).click();
  await expect(adminPage.getByRole('dialog')).not.toBeVisible();
  await page.goto(orderUrl);
  await expect(page.getByRole('heading',{name:'Your notes are ready.'})).toBeVisible();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download PDF'}).click();
  const download=await downloadPromise; expect(download.suggestedFilename()).toMatch(/\.pdf$/);
  await page.screenshot({path:testInfo.outputPath('approved-order.png'),fullPage:true});
  await adminContext.close();
});
test('catalogue fits a narrow mobile viewport',async({page})=>{
  await page.setViewportSize({width:320,height:740}); await page.goto('/');
  await expect(page.getByLabel('Search notes')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Toggle navigation'}).click();
  await expect(page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'My purchases'})).toBeVisible();
});
